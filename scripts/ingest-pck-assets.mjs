import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root=process.cwd(),source=path.resolve(root,process.argv[2]??'data/teacher/pck.assets.json'),output=path.resolve(root,process.argv[3]??'src/teaching/pckAssetCatalog.generated.ts');
const document=JSON.parse(fs.readFileSync(source,'utf8'));
if(document.schemaVersion!==1||!Array.isArray(document.assets))throw new Error('pck_document_schema_invalid');
const ids=new Set();
for(const [index,asset] of document.assets.entries()){
  const missing=[];
  for(const field of ['assetId','kind','domain','family','representation','learnerAction','confidence','status'])if(!asset[field])missing.push(field);
  if(!asset.provenance?.sourceKind||!asset.provenance?.sourceId)missing.push('provenance');
  if(!Array.isArray(asset.facets)||!asset.facets.length)missing.push('facets');
  if(!Array.isArray(asset.compatibleMechanismIds)||!asset.compatibleMechanismIds.length)missing.push('compatibleMechanismIds');
  if(ids.has(asset.assetId))throw new Error(`pck_duplicate_asset_id:${asset.assetId}`);ids.add(asset.assetId);
  if(asset.kind==='LEXICAL_SENSE_CONTRAST'&&!asset.lexical?.senseId&&!asset.lexical?.contextualSenseId)missing.push('exactSense');
  if(asset.kind==='EXAM_PROCEDURE'&&asset.examTiming?.languageAbilityInferenceAllowed!==false)missing.push('languageAbilityInferenceAllowed=false');
  if(asset.productionEligible&&(asset.status!=='PRODUCTION_ELIGIBLE'||asset.confidence!=='HIGH'||!asset.reviewedBy||!asset.reviewedAt))missing.push('reviewedProductionEligibility');
  if(missing.length)throw new Error(`pck_asset_invalid:${index}:${missing.join(',')}`);
}
const banner='// Generated by scripts/ingest-pck-assets.mjs from validated data. Do not hand-edit.\n';
const body=`export const bundledPckAssetValuesV1:readonly unknown[]=Object.freeze(${JSON.stringify(document.assets,null,2)});\n`;
fs.writeFileSync(output,banner+body,'utf8');
console.log(JSON.stringify({source,output,accepted:document.assets.length,productionEligible:document.assets.filter(asset=>asset.productionEligible).length},null,2));
